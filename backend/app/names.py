    # region — полка (Восток) или отдельная страна (jp); всё прочее берёт весь мир
    keys = _BY_KEY.get(region) or (
        (region,) if region in COUNTRIES else tuple(c for cs in _BY_KEY.values() for c in cs))
    out: list[dict] = []
    for _ in range(max(1, min(40, n))):
        kind = rnd.choice(shapes) if shape == "mix" else shape
        if kind == "xeno" and not world:
            name = rnd.choice(XENO)
            out.append({"name": name, "shape": "xeno", "first": name,
                        "family": "", "alias": "", "country": ""})
            continue
        country = rnd.choice(keys) if world else ""
        first, family = pools(pool, country)
        first = by_gender(first, country or "setting", gender)
        f = rnd.choice(first)
        fam = rnd.choice(family) if kind in ("full", "aliasfull") else ""
        if fam and f in FEMALE.get(country, frozenset()):
            fam = feminize(fam, country)
        al = rnd.choice(ALIAS) if kind in ("alias", "aliasfull") else ""
        name = " ".join(p for p in (f, fam) if p)
        if al:
            name = f"{name} {QUOTES[0]}{al}{QUOTES[1]}"
        out.append({"name": name, "shape": kind, "first": f, "family": fam,
                    "alias": al, "country": country,
                    "gender": "f" if f in FEMALE.get(country or "setting",
                                                     frozenset()) else "m"})
    return out


