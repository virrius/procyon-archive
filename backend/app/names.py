def feminize(family: str, country: str) -> str:
    """Женская форма фамилии: русская и польско-чешская её требуют."""
    if country == "ru":
        if family.endswith(("ов", "ев", "ёв", "ин", "ын")):
            return family + "а"
        if family.endswith(("ий", "ый", "ой")):
            return family[:-2] + "ая"
        return family
    if country == "pl":
        if family.endswith("ий"):
            return family[:-2] + "ая"
        if family.endswith(("а", "я")):
            return family
        return family + "ова"
    return family


